"""menu_font.py <out.h>: the in-game menu's font (vk_menu.c): Aileron Regular (dotcolon.net, CC0; the copy Pillow bundles as its default font, loaded
with ImageFont.load_default(size=...), so nothing is downloaded) for ASCII 32..126, as a signed distance field atlas: each glyph drawn at 4x its cell
size, the distance to its edge sampled per cell pixel (spread SPREAD pixels), 128 at the edge, packed into an ATLAS_W x ATLAS_H single-channel image.
Metrics in cell pixels of an EM-pixel font: advance, bearing, size and the atlas rectangle. Run by hand when the font changes; the header is kept in git."""
import sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

EM, UP, SPREAD, ATLAS_W, ATLAS_H = 40, 4, 6, 512, 512
font = ImageFont.load_default(size=EM * UP)
asc, desc = font.getmetrics()
glyphs, x, y, row_h = [], 1, 1, 0
atlas = np.zeros((ATLAS_H, ATLAS_W), np.uint8)
for c in range(32, 127):
    ch = chr(c)
    adv = font.getlength(ch) / UP
    l, t, r, b = font.getbbox(ch)   # relative to the drawing origin (top of the ascent)
    if r <= l or b <= t:   # a space
        glyphs.append((c, adv, 0, 0, 0, 0, 0, 0)); continue
    pad = SPREAD * UP
    W, H = r - l + 2 * pad, b - t + 2 * pad
    img = Image.new('L', (W, H), 0)
    ImageDraw.Draw(img).text((pad - l, pad - t), ch, font=font, fill=255)
    m = np.asarray(img) >= 128
    # edge points of the high-resolution mask
    e = m ^ np.pad(m, 1)[1:-1, 2:] | m ^ np.pad(m, 1)[1:-1, :-2] | m ^ np.pad(m, 1)[2:, 1:-1] | m ^ np.pad(m, 1)[:-2, 1:-1]
    ey, ex = np.nonzero(e)
    cw, chh = (W + UP - 1) // UP, (H + UP - 1) // UP
    gy, gx = np.mgrid[0:chh, 0:cw]
    sy, sx = gy * UP + UP / 2, gx * UP + UP / 2
    d = np.full((chh, cw), 1e9)
    for k in range(0, len(ex), 256):   # nearest edge point, in chunks
        dy = sy[..., None] - ey[k:k + 256]; dx = sx[..., None] - ex[k:k + 256]
        d = np.minimum(d, np.sqrt(dx * dx + dy * dy).min(axis=-1))
    inside = m[np.clip(sy.astype(int), 0, H - 1), np.clip(sx.astype(int), 0, W - 1)]
    sd = np.where(inside, d, -d) / UP   # cell pixels, positive inside
    v = np.clip(128 + sd * (127 / SPREAD), 0, 255).astype(np.uint8)
    if x + cw + 1 > ATLAS_W: x, y, row_h = 1, y + row_h + 1, 0
    if y + chh + 1 > ATLAS_H: sys.exit('the atlas is full')
    atlas[y:y + chh, x:x + cw] = v
    # bearing: the cell's top-left relative to the pen at the baseline (y down)
    bx, by = (l - pad) / UP, (t - pad) / UP - asc / UP
    glyphs.append((c, adv, bx, by, cw, chh, x, y))
    x += cw + 1; row_h = max(row_h, chh)
used_h = y + row_h + 1
out = open(sys.argv[1], 'w', newline='\n')
out.write('// Generated by menu_font.py from Aileron Regular (dotcolon.net, CC0; the copy Pillow bundles): the in-game menu\'s signed distance field font.\n')
out.write('// Do not edit: run "py -3 menu_font.py menu_font.h" again.\n#pragma once\n#include <stdint.h>\n')
out.write(f'enum {{ MF_EM = {EM}, MF_SPREAD = {SPREAD}, MF_W = {ATLAS_W}, MF_H = {used_h}, MF_ASCENT = {round(asc / UP)}, MF_DESCENT = {round(desc / UP)} }};\n')
out.write('typedef struct { float adv, bx, by; uint16_t w, h, x, y; } mf_glyph;   // ASCII 32..126: advance, bearing, cell size, atlas place\n')
out.write('static const mf_glyph mf_glyphs[95] = {\n')
for g in glyphs: out.write('    {%.3ff, %.3ff, %.3ff, %d, %d, %d, %d},   // %r\n' % (g[1], g[2], g[3], g[4], g[5], g[6], g[7], chr(g[0])))
out.write('};\nstatic const uint8_t mf_atlas[MF_W * MF_H] = {\n')
flat = atlas[:used_h].flatten()
for i in range(0, len(flat), 40): out.write('    ' + ','.join(str(int(b)) for b in flat[i:i + 40]) + ',\n')
out.write('};\n')
print(f'{len(glyphs)} glyphs, atlas {ATLAS_W}x{used_h}')
